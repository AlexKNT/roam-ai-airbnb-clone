export function resolvePlace(words: string): string {
  return placeAliases[words] ?? words;
}

/** Chips read "CA", never "Ca", and "Big Sur" keeps its capitals. */
export function placeLabel(place: string): string {
  if (place.length === 2) return place.toUpperCase();

  return place.replace(/\b[a-z]/g, (letter) => letter.toUpperCase());
}
